# Day 11 - Python Tuples

# Creating a tuple
fruits = ("apple", "banana", "mango", "orange")

# Printing the tuple
print(fruits)

# Accessing elements
print(fruits[0])
print(fruits[1])

# Negative indexing
print(fruits[-1])
print(fruits[-2])

# Tuple slicing
print(fruits[0:3])
print(fruits[1:])

# Tuple with different data types
my_tuple = ("Anusha", 20, 6.62, True)

print(my_tuple)
